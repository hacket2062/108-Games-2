type MathTuple = [
  id: string,
  grade: GradeLevel,
  semester: SemesterId,
  prompt: string,
  formulaShield: string,
  options: [string, string, string, string],
  correctIndex: number,
  explanation: string,
  hint: string,
  tag: string
];

function buildMath(rows: MathTuple[]): MathQuestion[] {
  return rows.map(([id, grade, semester, prompt, formulaShield, options, correctIndex, explanation, hint, knowledgeTag]) => {
    const type: MathQuestion['type'] =
      knowledgeTag.includes('面積') || knowledgeTag.includes('周長') || knowledgeTag.includes('角') || knowledgeTag.includes('體積') || knowledgeTag.includes('圓')
        ? 'geometry'
        : knowledgeTag.includes('分數') || knowledgeTag.includes('小數') || knowledgeTag.includes('比')
          ? 'fraction'
          : 'calc';
    return {
      id,
      grade,
      semester,
      subject: 'math',
      type,
      prompt,
      payload: { formulaShield, options, correctIndex },
      answer: options[correctIndex],
      explanation,
      hint,
      knowledgeTag,
    };
  });
}

