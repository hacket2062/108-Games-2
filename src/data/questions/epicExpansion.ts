// Compact builders to guarantee 100% schema consistency & rich authentic 108 Curriculum content
type ChSlashTuple = [
  id: string,
  grade: GradeLevel,
  semester: SemesterId,
  prompt: string,
  options: [string, string, string, string],
  correctIndex: number,
  explanation: string,
  hint: string,
  tag: string
];

type ChRadicalTuple = [
  id: string,
  grade: GradeLevel,
  semester: SemesterId,
  prompt: string,
  targetChar: string,
  parts: [string, string],
  distractors: [string, string],
  explanation: string,
  hint: string,
  tag: string
];

type ChTypoTuple = [
  id: string,
  grade: GradeLevel,
  semester: SemesterId,
  prompt: string,
  sentence: string,
  wrongIndex: number,
  correctChar: string,
  explanation: string,
  hint: string,
  tag: string
];

function buildChineseSlash(rows: ChSlashTuple[]): ChineseQuestion[] {
  return rows.map(([id, grade, semester, prompt, options, correctIndex, explanation, hint, knowledgeTag]) => ({
    id,
    grade,
    semester,
    subject: 'chinese',
    type: 'slash',
    prompt,
    payload: { mode: 'slash', options, correctIndex },
    answer: options[correctIndex],
    explanation,
    hint,
    knowledgeTag,
  }));
}

function buildChineseRadical(rows: ChRadicalTuple[]): ChineseQuestion[] {
  return rows.map(([id, grade, semester, prompt, targetChar, parts, distractors, explanation, hint, knowledgeTag]) => ({
    id,
    grade,
    semester,
    subject: 'chinese',
    type: 'radical',
    prompt,
    payload: {
      mode: 'radical',
      partA: parts[0],
      partB: parts[1],
      pool: [parts[0], distractors[0], parts[1], distractors[1]],
      targetChar,
      meaning: hint,
    },
    answer: targetChar,
    explanation,
    hint,
    knowledgeTag,
  }));
}

function buildChineseTypo(rows: ChTypoTuple[]): ChineseQuestion[] {
  return rows.map(([id, grade, semester, prompt, sentence, wrongIndex, correctChar, explanation, hint, knowledgeTag]) => ({
    id,
    grade,
    semester,
    subject: 'chinese',
    type: 'typo',
    prompt,
    payload: {
      mode: 'typo',
      sentence,
      typoIndex: wrongIndex,
      wrongChar: sentence[wrongIndex] ?? sentence[sentence.length - 1],
      correctChar,
    },
    answer: correctChar,
    explanation,
    hint,
    knowledgeTag,
  }));
}

