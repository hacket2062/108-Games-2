type SciTuple = [
  id: string,
  grade: GradeLevel,
  semester: SemesterId,
  dishName: string,
  orderReq: string,
  correct1: string,
  correct2: string,
  wrong1: string,
  wrong1Reason: string,
  wrong2: string,
  wrong2Reason: string,
  tempZone: 'freeze' | 'simmer' | 'boil',
  tempLabel: string,
  ph: 'acid' | 'neutral' | 'alkali',
  phLabel: string,
  effectStyle: 'rainbow' | 'ice' | 'fire' | 'electric' | 'nature',
  explanation: string,
  hint: string,
  tag: string
];

function buildScience(rows: SciTuple[]): ScienceQuestion[] {
  return rows.map(
    ([
      id,
      grade,
      semester,
      dishName,
      orderRequirement,
      c1,
      c2,
      w1,
      w1r,
      w2,
      w2r,
      targetTempZone,
      targetTempLabel,
      targetPh,
      targetPhLabel,
      effectStyle,
      explanation,
      hint,
      knowledgeTag,
    ]) => ({
      id,
      grade,
      semester,
      subject: 'science',
      type: 'dish',
      prompt: `製作「${dishName}」：${orderRequirement}`,
      payload: {
        dishName,
        orderRequirement,
        neededCount: 2,
        ingredients: [
          { id: `${id}-1`, name: c1, categoryTag: knowledgeTag, color: '#38BDF8', accent: '#BAE6FD', isCorrect: true },
          { id: `${id}-2`, name: c2, categoryTag: knowledgeTag, color: '#34D399', accent: '#A7F3D0', isCorrect: true },
          { id: `${id}-3`, name: w1, categoryTag: knowledgeTag, color: '#F59E0B', accent: '#FDE68A', isCorrect: false, wrongReason: w1r },
          { id: `${id}-4`, name: w2, categoryTag: knowledgeTag, color: '#F43F5E', accent: '#FECDD3', isCorrect: false, wrongReason: w2r },
        ],
        targetTempZone,
        targetTempLabel,
        targetPh,
        targetPhLabel,
        effectStyle: effectStyle === 'electric' ? 'rainbow' : effectStyle,
      },
      answer: `${c1}＋${c2}`,
      explanation,
      hint,
      knowledgeTag,
    })
  );
}

